-- Atlas database schema.
-- Run once in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.
-- Safe to re-run: it only creates what is missing and seeds the demo ticket once.
-- For a new project, also run supabase/migrations/003_support_bot.sql (support bot tables and articles).

create table if not exists customers (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  email text not null unique,
  location text,
  device text,
  orders integer not null default 0,
  csat integer,
  created_at timestamptz not null default now()
);

create table if not exists tickets (
  id bigint generated by default as identity (start with 5000) primary key,
  customer_id uuid not null references customers (id),
  subject text not null,
  description text not null default '',
  summary text not null default '',
  intent text not null default 'General Support',
  sentiment text not null default 'Neutral',
  confidence integer not null default 0,
  priority text not null default 'Medium'
    check (priority in ('Low', 'Medium', 'High', 'Urgent')),
  status text not null default 'Open'
    check (status in ('Open', 'Pending', 'Waiting on Customer', 'Escalated', 'Resolved', 'Closed')),
  assigned_to text not null default 'Unassigned',
  channel text not null default 'Chat',
  category text not null default 'General Support',
  tags text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists ticket_messages (
  id bigint generated always as identity primary key,
  ticket_id bigint not null references tickets (id) on delete cascade,
  sender text not null,
  role text not null check (role in ('customer', 'agent')),
  body text not null,
  created_at timestamptz not null default now()
);

create table if not exists ticket_activities (
  id bigint generated always as identity primary key,
  ticket_id bigint not null references tickets (id) on delete cascade,
  title text not null,
  color text not null default 'bg-zinc-500',
  created_at timestamptz not null default now()
);

create table if not exists ticket_notes (
  id bigint generated always as identity primary key,
  ticket_id bigint not null references tickets (id) on delete cascade,
  author text not null,
  body text not null,
  created_at timestamptz not null default now()
);

create index if not exists ticket_messages_ticket_id_idx on ticket_messages (ticket_id, created_at);
create index if not exists ticket_activities_ticket_id_idx on ticket_activities (ticket_id, created_at);
create index if not exists ticket_notes_ticket_id_idx on ticket_notes (ticket_id, created_at);
create index if not exists tickets_created_at_idx on tickets (created_at desc);

-- Row Level Security on, with no policies: the browser (anon key) can't read
-- or write anything. The Next.js server uses the secret key, which bypasses RLS.
alter table customers enable row level security;
alter table tickets enable row level security;
alter table ticket_messages enable row level security;
alter table ticket_activities enable row level security;
alter table ticket_notes enable row level security;

